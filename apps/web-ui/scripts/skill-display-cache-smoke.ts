import assert from "node:assert/strict";
import { clearDisplayCaches, createDisplayCache, invalidateDisplayCaches } from "../src/display-cache";

const cache = createDisplayCache<string[]>();
let calls = 0;
let finish!: (value: string[]) => void;
const load = () => { calls++; return new Promise<string[]>((resolve) => { finish = resolve; }); };
const first = cache.load(load);
const parallel = cache.load(load);
assert.equal(calls, 1);
assert.equal(first, parallel);
finish(["saved"]);
await first;
assert.deepEqual(cache.peek(), ["saved"]);
await cache.load(load);
assert.equal(calls, 1, "opening another local view reuses display metadata");
const old = cache.load(load, true);
cache.invalidate();
finish(["obsolete"]);
await old;
assert.deepEqual(cache.peek(), ["saved"], "a request from before a mutation cannot replace the cache");
await assert.rejects(cache.load(async () => { throw new Error("offline"); }, true), /offline/);
assert.deepEqual(cache.peek(), ["saved"], "offline failures keep local metadata visible");
assert.deepEqual(await cache.load(async () => ["fresh"]), ["fresh"], "invalidated data reloads without an explicit refresh flag");
const sources = createDisplayCache<string[]>();
await sources.load(async () => ["source count before delete"]);
invalidateDisplayCaches();
assert.deepEqual(cache.peek(), ["fresh"], "mutations retain display data during the refresh");
assert.deepEqual(await sources.load(async () => ["source count after delete"]), ["source count after delete"], "skill changes invalidate source metadata too");
clearDisplayCaches();
assert.equal(cache.peek(), undefined, "profile/logout clears display data");
console.log("Skill display cache smoke passed.");
