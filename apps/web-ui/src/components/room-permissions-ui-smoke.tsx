globalThis.fetch = (async (input: RequestInfo | URL, init?: RequestInit) => {
	const url = String(input);
	const method = init?.method ?? "GET";
	if (url.endsWith("/workspace-default")) {
		policyRequests.push(`${method} ${url}`);
		if (method === "DELETE") {
			if (deferredClear && url.includes("/room1/")) await deferredClear;
			if (rejectClear) return new Response(JSON.stringify({ error: "clear failed" }), { status: 500 });
			return new Response(JSON.stringify({ policy: null, warnings: [], deleted: true }));
		}
		if (url.includes("/room2/")) return new Response(JSON.stringify({ policy: otherPolicy, warnings: [] }));
		if (method === "GET" && deferredPolicyGet && url.includes("/room1/")) await deferredPolicyGet;
		if (method === "PUT") {
			if (deferredPolicySave) await deferredPolicySave;
			if (rejectWorkspaceSave) return new Response('{"error":"policy save failed"}', { status: 500 });
			const update = JSON.parse(String(init?.body));
			policyWrites.push(update);
			savedPolicy = { ...savedPolicy, workspaceAccessMode: update.workspaceAccessMode, bashEnabled: update.bashEnabled, allowedToolNames: update.toolSelection.allowedToolNames, roots: update.root ? [{ displayLabel: update.root, basename: update.root }] : savedPolicy.roots };
		}
		return new Response(JSON.stringify({ policy: savedPolicy, warnings: [] }));
	}
	if (url.endsWith("/permissions")) {
		permissionRequests.push(`${method} ${url}`);
		if (method === "PUT") {
			if (deferredPermissionsPut && url.includes("/room1/")) await deferredPermissionsPut;
			if (rejectPermissionsPut) return new Response('{"error":"permission PUT denied"}', { status: 403 });
			bodies.push(String(init?.body));
			permissionsText = JSON.stringify({ exists: true, document: JSON.parse(String(init?.body)), error: null });
			return new Response(permissionsText);
		}
		if (queuedPermissionsGet && url.includes("/room1/")) {
			const pending = queuedPermissionsGet;
			const snapshot = queuedPermissionsSnapshot ?? permissionsText;
			queuedPermissionsGet = null;
			await pending;
			return new Response(snapshot);
		}
		if (deferredPermissionsGet && url.includes("/room1/") && (deferAllPermissionsGets || deferOnlyNextPermissionsGet)) {
			deferOnlyNextPermissionsGet = false;
			await deferredPermissionsGet;
		}
		if (permissionsFail) return new Response('{"exists":true,"document":null,"error":"permissions.json is invalid"}');
		return new Response(permissionsText);
	}
	if (url === "/api/remote/client-context") return new Response(JSON.stringify({ remote: false, capability: "full", sharedServer: false }));
	return new Response(JSON.stringify({ remote: false, capability: "full" }));
}) as typeof fetch;

